// server/controllers/aiController.js
const axios = require('axios');

const ACTION_PROMPTS = {
  explain_selection: 'Please provide a clear, concise, line-by-line explanation of the following selected code snippet:',
  explain_file: 'Please explain the overall architecture, purpose, and key logic of this complete file:',
  detect_bugs: 'Thoroughly analyze this code for potential bugs, logical errors, edge cases, memory leaks, and performance bottlenecks:',
  suggest_fixes: 'Identify the issues in this code and provide corrected, production-ready code with an explanation of the fix:',
  generate_code: 'Generate clean, modern, well-typed code based on the following instruction:',
  optimize: 'Optimize this code for time complexity (Big-O), memory efficiency, and readability. Explain the optimization improvements:',
  generate_docs: 'Generate comprehensive documentation (such as JSDoc or docstrings) and usage examples for this code:',
  generate_comments: 'Add clean, descriptive inline comments explaining the logic of this code:',
  explain_error: 'Analyze this compilation or runtime error in the context of the code and explain how to resolve it:',
  best_practices: 'Review this code against modern software engineering best practices, security standards, and style guidelines:',
  generate_tests: 'Generate comprehensive unit tests (including happy path and edge cases) for this code:',
  convert_language: 'Convert the following code into the target language, preserving exact functionality and using idioms of the target language:',
  chat: 'Assist the developer with their programming query:',
};

// @desc Query AI assistant with context
// @route POST /api/ai/query
exports.queryAI = async (req, res) => {
  const {
    prompt,
    action = 'chat',
    code = '',
    selectedCode = '',
    language = 'javascript',
    fileName = 'main',
    errorContext = '',
    targetLanguage = '',
  } = req.body;

  const geminiApiKey = process.env.GEMINI_API_KEY;
  const openaiApiKey = process.env.OPENAI_API_KEY;

  // If no AI API key is configured, return clear instructions without fake responses
  if (!geminiApiKey && !openaiApiKey) {
    return res.status(200).json({
      configured: false,
      message:
        'AI Assistant requires an API key. To enable AI features, add GEMINI_API_KEY or OPENAI_API_KEY to your server/.env file and restart the server.',
      help: {
        gemini: 'Get a free Gemini API key from https://aistudio.google.com/app/apikey',
        openai: 'Get an OpenAI API key from https://platform.openai.com/api-keys',
      },
    });
  }

  // Construct context-rich system instruction
  const actionPrefix = ACTION_PROMPTS[action] || ACTION_PROMPTS.chat;
  let fullPrompt = `${actionPrefix}\n\n`;

  if (targetLanguage) {
    fullPrompt += `Target Language: ${targetLanguage}\n`;
  }
  if (fileName) {
    fullPrompt += `Active File: ${fileName} (${language})\n`;
  }
  if (selectedCode) {
    fullPrompt += `--- Selected Code Snippet ---\n\`\`\`${language}\n${selectedCode}\n\`\`\`\n\n`;
  }
  if (code && !selectedCode) {
    fullPrompt += `--- File Content ---\n\`\`\`${language}\n${code}\n\`\`\`\n\n`;
  }
  if (errorContext) {
    fullPrompt += `--- Execution Error Output ---\n${errorContext}\n\n`;
  }
  if (prompt) {
    fullPrompt += `User Instructions: ${prompt}\n`;
  }

  fullPrompt += `\nGuidelines:
- Provide direct, concise, and helpful answers.
- Format code blocks using markdown with proper language tags (e.g., \`\`\`${language}).
- Point out potential bugs, edge cases, and best practices.`;

  try {
    let aiResponseText = '';

    // 1. Google Gemini API
    if (geminiApiKey) {
      const geminiUrl = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${geminiApiKey}`;
      const geminiBody = {
        contents: [
          {
            role: 'user',
            parts: [{ text: fullPrompt }],
          },
        ],
        generationConfig: {
          temperature: 0.2,
          maxOutputTokens: 2048,
        },
      };

      const resp = await axios.post(geminiUrl, geminiBody, { timeout: 25000 });
      aiResponseText =
        resp.data?.candidates?.[0]?.content?.parts?.[0]?.text ||
        'No response generated by AI model.';
    }
    // 2. OpenAI API
    else if (openaiApiKey) {
      const openaiUrl = 'https://api.openai.com/v1/chat/completions';
      const openaiBody = {
        model: 'gpt-4o-mini',
        messages: [
          {
            role: 'system',
            content:
              'You are CollabCode AI, an expert software engineer and pair-programming assistant inside the CollabCode collaborative IDE.',
          },
          { role: 'user', content: fullPrompt },
        ],
        temperature: 0.2,
        max_tokens: 2048,
      };

      const resp = await axios.post(openaiUrl, openaiBody, {
        headers: { Authorization: `Bearer ${openaiApiKey}` },
        timeout: 25000,
      });
      aiResponseText = resp.data?.choices?.[0]?.message?.content || 'No response generated.';
    }

    res.json({
      configured: true,
      reply: aiResponseText,
      action,
    });
  } catch (apiErr) {
    console.error('[AI Assistant] API call error:', apiErr.response?.data || apiErr.message);
    const errMsg = apiErr.response?.data?.error?.message || apiErr.message || 'AI service request failed';
    res.status(502).json({
      configured: true,
      error: true,
      message: `AI service error: ${errMsg}`,
    });
  }
};
